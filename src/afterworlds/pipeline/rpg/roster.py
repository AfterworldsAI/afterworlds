def require(template: str, entry: str) -> None:
    """Refuse an entry outside :data:`EXECUTABLE`."""
    if f"{template}:{entry}" not in EXECUTABLE:
        raise AdjudicationRefusal(
            RefusalKind.UNSUPPORTED_CAPABILITY,
            f"{template}/{entry} prints mechanics not executed here",
        )
